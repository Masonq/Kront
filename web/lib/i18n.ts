export function deepCyr<T>(o: T): T {
  if (typeof o === "string") return toCyr(o) as T;
  if (typeof o === "function") return ((...a: unknown[]) => toCyr((o as (...x: unknown[]) => string)(...a))) as T;
  if (Array.isArray(o)) return o.map(deepCyr) as T;
  if (o && typeof o === "object") return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, deepCyr(v)])) as T;
  return o;
}

const srCyrl = deepCyr(sr);
export function dict(l: Lang): Dict {
  return l === "ru" ? ru : l === "sr-cyrl" ? srCyrl : sr;
}
export type { Dict };

/** Текст из API: для кириллицы переводим латиницу в кириллицу */
export function tx(l: Lang, s: string): string {
  return l === "sr-cyrl" ? toCyr(s) : s;
}
